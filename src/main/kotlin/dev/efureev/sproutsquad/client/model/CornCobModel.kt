package dev.efureev.sproutsquad.client.model

import joshxviii.plantz.pazResource
import joshxviii.plantz.renderer.entity.ProjectileRenderState
import net.minecraft.client.model.EntityModel
import net.minecraft.client.model.geom.ModelLayerLocation
import net.minecraft.client.model.geom.ModelPart
import net.minecraft.client.model.geom.PartPose
import net.minecraft.client.model.geom.builders.CubeListBuilder
import net.minecraft.client.model.geom.builders.LayerDefinition
import net.minecraft.client.model.geom.builders.MeshDefinition

/**
 * The Corn Cannon's flying cob, as big as the one in its mouth: the same cone at both ends, no flame or smoke. Built along y with the nose
 * at -y and turned like the original's MissileModel, so ProjectileRenderer points it along the flight.
 * Texture 128×64 from `art/corn_cannon/draw_corn_cannon.py`.
 */
class CornCobModel(root: ModelPart) : EntityModel<ProjectileRenderState>(root) {
    companion object {
        @JvmField val LAYER_LOCATION = ModelLayerLocation(pazResource("corn_cob"), "main")

        fun createBodyLayer(): LayerDefinition {
            val mesh = MeshDefinition()
            // region generated by art/corn_cannon/draw_corn_cannon.py
            mesh.root.addOrReplaceChild("cob", CubeListBuilder.create()
                .texOffs(72, 35).addBox(-2f, 16f, -2f, 4f, 2f, 4f)  // end_back
                .texOffs(0, 35).addBox(-3f, 12f, -3f, 6f, 4f, 6f)  // tip_back_core
                .texOffs(24, 35).addBox(-2f, 13f, -4f, 4f, 2f, 8f)  // tip_back_wide
                .texOffs(48, 35).addBox(-4f, 13f, -2f, 8f, 2f, 4f)  // tip_back_tall
                .texOffs(0, 0).addBox(-5f, -12f, -5f, 10f, 25f, 10f)  // cob_core
                .texOffs(40, 0).addBox(-3f, -11f, -6f, 6f, 23f, 12f)  // cob_wide
                .texOffs(76, 0).addBox(-6f, -11f, -3f, 12f, 23f, 6f)  // cob_tall
                .texOffs(0, 35).addBox(-3f, -15f, -3f, 6f, 4f, 6f)  // tip_core
                .texOffs(24, 35).addBox(-2f, -14f, -4f, 4f, 2f, 8f)  // tip_wide
                .texOffs(48, 35).addBox(-4f, -14f, -2f, 8f, 2f, 4f)  // tip_tall
                .texOffs(72, 35).addBox(-2f, -17f, -2f, 4f, 2f, 4f),  // end
                PartPose.offsetAndRotation(0f, 24f, 0f, 0f, -1.5708f, 1.5708f))
            // endregion
            return LayerDefinition.create(mesh, 128, 64)
        }
    }
}
