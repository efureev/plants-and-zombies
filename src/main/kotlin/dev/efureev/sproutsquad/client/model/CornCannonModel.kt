/**
 * Corn Cannon: an ear of corn whose husk has opened at the front into a cannon's mouth, the cob looking out of
 * it; two eyes bulge over the mouth, corn silk on top, a curly tendril at the back. Drawn at its real size
 * (1 texel = 1/16 block), about 3.6 blocks long.
 *
 * Parts: body (turns with the head, like the Melon Pult) → husk (tilts about its bottom near the tail) →
 * cob, petal_left / petal_right / petal_low (the opened husk leaves), silk, tendril; ground (the hub and its six
 * leaves, does not turn). The boxes and the 256×128 texture come from `art/corn_cannon/draw_corn_cannon.py`,
 * which rewrites the generated region below.
 *
 * The cob is gone after a shot and grows back while the plant cools down (CornCannon.COOLDOWN ticks):
 * it slides out of the husk from deep inside, growing from half size (CornCannon.cobGrowth, passed as the pose).
 * While it is small, the dark mouth painted on the front of the husk shows.
 */
class CornCannonModel(root: ModelPart) : SquadPlantModel(
    root,
    init = CornCannonAnimation.init,
    idle = CornCannonAnimation.idle,
    action = CornCannonAnimation.action,
    sleep = CornCannonAnimation.sleep,
) {
    private val body = root.getChild("body")
    private val husk = body.getChild("husk")
    private val cob = husk.getChild("cob")

    override fun setupAnim(state: PlantRenderState) {
        super.setupAnim(state)
        body.yRot += state.yRot * Mth.DEG_TO_RAD
        val grown = state.squadPose / 1000f // CornCannon.cobGrowth(), by the cooldown the shot started
        val size = 0.5f + 0.5f * grown
        cob.z += (1f - grown) * COB_RETRACT
        cob.xScale *= size
        cob.yScale *= size
        cob.zScale *= size
        cob.visible = grown > 0f
    }

    companion object {
        @JvmField val LAYER_LOCATION = ModelLayerLocation(pazResource("corn_cannon"), "main")

        /** How far back into the husk an empty cob sits, in pixels. */
        private const val COB_RETRACT = 24f

        fun createBodyLayer(): LayerDefinition {
            val mesh = MeshDefinition()
            // region generated by art/corn_cannon/draw_corn_cannon.py
            val body = mesh.root.addOrReplaceChild("body", CubeListBuilder.create(),
                PartPose.offset(0f, 24f, 0f))
            val husk = body.addOrReplaceChild("husk", CubeListBuilder.create()
                .texOffs(88, 90).addBox(-6f, -13f, 10f, 12f, 6f, 3f)  // tail_wide
                .texOffs(122, 70).addBox(-3f, -16f, 9f, 6f, 12f, 5f)  // tail_tall
                .texOffs(76, 70).addBox(-8f, -15f, 1f, 16f, 10f, 7f)  // rear_wide
                .texOffs(122, 41).addBox(-5f, -18f, 0f, 10f, 16f, 9f)  // rear_tall
                .texOffs(132, 0).addBox(-10f, -17f, -20f, 20f, 14f, 19f)  // main_wide
                .texOffs(0, 0).addBox(-7f, -20f, -21f, 14f, 20f, 21f)  // main_tall
                .texOffs(144, 70).addBox(-9f, -24f, -20f, 7f, 8f, 6f)  // eye_left
                .texOffs(170, 70).addBox(2f, -24f, -20f, 7f, 8f, 6f),  // eye_right
                PartPose.offset(0f, -2f, 15f))
            val cob = husk.addOrReplaceChild("cob", CubeListBuilder.create()
                .texOffs(0, 41).addBox(-6f, -4f, -22f, 12f, 8f, 21f)  // cob_wide
                .texOffs(70, 0).addBox(-4f, -6f, -23f, 8f, 12f, 23f)  // cob_tall
                .texOffs(32, 90).addBox(-4f, -4f, -26f, 8f, 8f, 3f)  // cob_tip
                .texOffs(184, 90).addBox(-2f, -2f, -28f, 4f, 4f, 2f),  // cob_end
                PartPose.offset(0f, -10f, -15f))
            val petal_left = husk.addOrReplaceChild("petal_left", CubeListBuilder.create()
                .texOffs(66, 41).addBox(0f, -8f, -13f, 1f, 16f, 13f),  // petal_left
                PartPose.offsetAndRotation(-10f, -10f, -20f, 0f, 0.5236f, 0f))
            val petal_right = husk.addOrReplaceChild("petal_right", CubeListBuilder.create()
                .texOffs(94, 41).addBox(-1f, -8f, -13f, 1f, 16f, 13f),  // petal_right
                PartPose.offsetAndRotation(10f, -10f, -20f, 0f, -0.5236f, 0f))
            val petal_low = husk.addOrReplaceChild("petal_low", CubeListBuilder.create()
                .texOffs(204, 70).addBox(-7f, 0f, -10f, 14f, 1f, 10f),  // petal_low
                PartPose.offsetAndRotation(0f, -1f, -20f, 0.20944f, 0f, 0f))
            val silk = husk.addOrReplaceChild("silk", CubeListBuilder.create()
                .texOffs(158, 90).addBox(-3f, -5f, 1f, 1f, 6f, 1f)  // silk_1
                .texOffs(84, 90).addBox(-1f, -8f, -1f, 1f, 9f, 1f)  // silk_2
                .texOffs(140, 90).addBox(0f, -6f, 0f, 1f, 7f, 1f)  // silk_3
                .texOffs(136, 90).addBox(1f, -7f, -2f, 1f, 8f, 1f)  // silk_4
                .texOffs(204, 90).addBox(2f, -4f, 1f, 1f, 5f, 1f),  // silk_5
                PartPose.offsetAndRotation(0f, -20f, -8f, -0.43633f, 0f, 0f))
            val tendril = husk.addOrReplaceChild("tendril", CubeListBuilder.create()
                .texOffs(144, 90).addBox(-1f, -1f, 0f, 2f, 2f, 5f)  // tendril_1
                .texOffs(196, 70).addBox(-1f, -10f, 5f, 2f, 11f, 2f)  // tendril_2
                .texOffs(118, 90).addBox(-1f, -12f, 0f, 2f, 2f, 7f)  // tendril_3
                .texOffs(196, 90).addBox(-1f, -10f, 0f, 2f, 4f, 2f)  // tendril_4
                .texOffs(208, 90).addBox(-1f, -8f, 2f, 2f, 2f, 2f)  // tendril_5
                .texOffs(162, 90).addBox(-3f, -13f, 6f, 6f, 1f, 5f),  // tendril_leaf
                PartPose.offset(0f, -10f, 14f))
            val ground = mesh.root.addOrReplaceChild("ground", CubeListBuilder.create()
                .texOffs(0, 70).addBox(-10f, -2f, -9f, 20f, 2f, 18f)  // hub_wide
                .texOffs(160, 41).addBox(-5f, -3f, -10f, 10f, 3f, 20f),  // hub_tall
                PartPose.offset(0f, 24f, 0f))
            val leaf_0 = ground.addOrReplaceChild("leaf_0", CubeListBuilder.create()
                .texOffs(54, 90).addBox(-3f, -2f, -17f, 6f, 1f, 9f)  // leaf_0_base
                .texOffs(0, 90).addBox(-3f, -1f, -27f, 6f, 1f, 10f),  // leaf_0_tip
                PartPose.offsetAndRotation(0f, 0f, 0f, 0f, 0.5236f, 0f))
            val leaf_1 = ground.addOrReplaceChild("leaf_1", CubeListBuilder.create()
                .texOffs(54, 90).addBox(-3f, -2f, -17f, 6f, 1f, 9f)  // leaf_1_base
                .texOffs(0, 90).addBox(-3f, -1f, -27f, 6f, 1f, 10f),  // leaf_1_tip
                PartPose.offsetAndRotation(0f, 0f, 0f, 0f, 1.5708f, 0f))
            val leaf_2 = ground.addOrReplaceChild("leaf_2", CubeListBuilder.create()
                .texOffs(54, 90).addBox(-3f, -2f, -17f, 6f, 1f, 9f)  // leaf_2_base
                .texOffs(0, 90).addBox(-3f, -1f, -27f, 6f, 1f, 10f),  // leaf_2_tip
                PartPose.offsetAndRotation(0f, 0f, 0f, 0f, 2.61799f, 0f))
            val leaf_3 = ground.addOrReplaceChild("leaf_3", CubeListBuilder.create()
                .texOffs(54, 90).addBox(-3f, -2f, -17f, 6f, 1f, 9f)  // leaf_3_base
                .texOffs(0, 90).addBox(-3f, -1f, -27f, 6f, 1f, 10f),  // leaf_3_tip
                PartPose.offsetAndRotation(0f, 0f, 0f, 0f, 3.66519f, 0f))
            val leaf_4 = ground.addOrReplaceChild("leaf_4", CubeListBuilder.create()
                .texOffs(54, 90).addBox(-3f, -2f, -17f, 6f, 1f, 9f)  // leaf_4_base
                .texOffs(0, 90).addBox(-3f, -1f, -27f, 6f, 1f, 10f),  // leaf_4_tip
                PartPose.offsetAndRotation(0f, 0f, 0f, 0f, 4.71239f, 0f))
            val leaf_5 = ground.addOrReplaceChild("leaf_5", CubeListBuilder.create()
                .texOffs(54, 90).addBox(-3f, -2f, -17f, 6f, 1f, 9f)  // leaf_5_base
                .texOffs(0, 90).addBox(-3f, -1f, -27f, 6f, 1f, 10f),  // leaf_5_tip
                PartPose.offsetAndRotation(0f, 0f, 0f, 0f, 5.75959f, 0f))
            // endregion
            return LayerDefinition.create(mesh, 256, 128)
        }
    }
}

/** Keyframes for [CornCannonModel]: rotations in degrees (negative X lifts the nose), positions in pixels. */
object CornCannonAnimation {
    private fun rot(t: Float, x: Float, y: Float, z: Float) = Keyframe(t, degreeVec(x, y, z), CATMULLROM)
    private fun pos(t: Float, x: Float, y: Float, z: Float) = Keyframe(t, posVec(x, y, z), CATMULLROM)
    private fun scale(t: Float, x: Float, y: Float, z: Float) = Keyframe(t, scaleVec(x.toDouble(), y.toDouble(), z.toDouble()), CATMULLROM)

    /** The husk swells up out of its leaves (the cob then grows out of it, see the model). */
    val init: AnimationDefinition = AnimationDefinition.Builder.withLength(1.0f)
        .addAnimation("husk", AnimationChannel(SCALE,
            Keyframe(0f, scaleVec(0.2, 0.0, 0.2), LINEAR), scale(0.4f, 1.1f, 1.15f, 1.05f), scale(0.7f, 0.97f, 0.95f, 1f), scale(1f, 1f, 1f, 1f)))
        .addAnimation("ground", AnimationChannel(SCALE,
            Keyframe(0f, scaleVec(0.0, 1.0, 0.0), LINEAR), scale(0.3f, 1.1f, 1f, 1.1f), scale(0.5f, 1f, 1f, 1f)))
        .build()

    /** It breathes a little, the opened husk leaves stir and its tendril sways. */
    val idle: AnimationDefinition = AnimationDefinition.Builder.withLength(3.0f).looping()
        .addAnimation("husk", AnimationChannel(SCALE,
            scale(0f, 1f, 1f, 1f), scale(1.5f, 1.02f, 1.03f, 1f), scale(3f, 1f, 1f, 1f)))
        .addAnimation("petal_left", AnimationChannel(ROTATION, rot(0f, 0f, 0f, 0f), rot(1.5f, 0f, 4f, 0f), rot(3f, 0f, 0f, 0f)))
        .addAnimation("petal_right", AnimationChannel(ROTATION, rot(0f, 0f, 0f, 0f), rot(1.5f, 0f, -4f, 0f), rot(3f, 0f, 0f, 0f)))
        .addAnimation("silk", AnimationChannel(ROTATION, rot(0f, 0f, 0f, 0f), rot(1.5f, -8f, 0f, 0f), rot(3f, 0f, 0f, 0f)))
        .addAnimation("tendril", AnimationChannel(ROTATION,
            rot(0f, 0f, 0f, 0f), rot(0.75f, 0f, 0f, 12f), rot(1.5f, 0f, 0f, 0f), rot(2.25f, 0f, 0f, -12f), rot(3f, 0f, 0f, 0f)))
        .build()

    /**
     * A shot: the nose lifts, the husk leaves fling open as the cob leaves about 0.5 s in (CornCannon.ACTION_DELAY),
     * the husk kicks back and settles.
     */
    val action: AnimationDefinition = AnimationDefinition.Builder.withLength(CornCannon.SHOT_ANIMATION_TICKS / 20f)
        .addAnimation("husk", AnimationChannel(ROTATION,
            rot(0f, 0f, 0f, 0f), rot(0.45f, -18f, 0f, 0f), rot(0.6f, -22f, 0f, 0f), rot(0.8f, -6f, 0f, 0f), rot(1.1f, 0f, 0f, 0f)))
        .addAnimation("husk", AnimationChannel(POSITION,
            pos(0f, 0f, 0f, 0f), pos(0.5f, 0f, 0f, 0f), pos(0.6f, 0f, 0f, 4f), pos(1.1f, 0f, 0f, 0f)))
        .addAnimation("petal_left", AnimationChannel(ROTATION,
            rot(0f, 0f, 0f, 0f), rot(0.45f, 0f, -6f, 0f), rot(0.6f, 0f, 24f, 0f), rot(0.9f, 0f, 6f, 0f), rot(1.1f, 0f, 0f, 0f)))
        .addAnimation("petal_right", AnimationChannel(ROTATION,
            rot(0f, 0f, 0f, 0f), rot(0.45f, 0f, 6f, 0f), rot(0.6f, 0f, -24f, 0f), rot(0.9f, 0f, -6f, 0f), rot(1.1f, 0f, 0f, 0f)))
        .addAnimation("petal_low", AnimationChannel(ROTATION,
            rot(0f, 0f, 0f, 0f), rot(0.45f, -5f, 0f, 0f), rot(0.6f, 20f, 0f, 0f), rot(0.9f, 5f, 0f, 0f), rot(1.1f, 0f, 0f, 0f)))
        .addAnimation("silk", AnimationChannel(ROTATION,
            rot(0f, 0f, 0f, 0f), rot(0.55f, 20f, 0f, 0f), rot(0.8f, -15f, 0f, 0f), rot(1.1f, 0f, 0f, 0f)))
        .addAnimation("tendril", AnimationChannel(ROTATION,
            rot(0f, 0f, 0f, 0f), rot(0.55f, 25f, 0f, 0f), rot(0.8f, -10f, 0f, 0f), rot(1.1f, 0f, 0f, 0f)))
        .build()

    /** It does not sleep at night; this pose (the nose droops, the leaves close) only completes the set. */
    val sleep: AnimationDefinition = AnimationDefinition.Builder.withLength(1.0f).looping()
        .addAnimation("husk", AnimationChannel(ROTATION, rot(0f, 6f, 0f, 0f), rot(1f, 6f, 0f, 0f)))
        .addAnimation("petal_left", AnimationChannel(ROTATION, rot(0f, 0f, -15f, 0f), rot(1f, 0f, -15f, 0f)))
        .addAnimation("petal_right", AnimationChannel(ROTATION, rot(0f, 0f, 15f, 0f), rot(1f, 0f, 15f, 0f)))
        .addAnimation("tendril", AnimationChannel(ROTATION, rot(0f, 30f, 0f, 0f), rot(1f, 30f, 0f, 0f)))
        .build()
}
